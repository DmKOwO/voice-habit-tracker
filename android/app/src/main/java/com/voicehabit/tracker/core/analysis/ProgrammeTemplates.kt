package com.voicehabit.tracker.core.analysis

/**
 * P1. Встроенный шаблон программы.
 *
 * ## Зачем он нужен рядом с вставкой текста
 *
 * Вставка из буфера требует, чтобы у человека уже был документ. Шаблон даёт
 * работающий пример в один тап: человек видит, какая структура ожидается, и
 * понимает, что сможет принести так же свою программу.
 *
 * ## Формат — тот же, что у `.docx`
 *
 * Текст проходит через [ProgrammeParser], а не через отдельный разбор. Иначе
 * встроенная программа и импортированная вели бы себя по-разному, и через
 * месяц никто не вспомнит, почему.
 *
 * ## Почему Пн/Ср/Пт
 *
 * Сплит 3/4/7 — самая частая схема для начинающего калистениста, и она
 * специально проверяет главное требование: тренировка активна **только** в
 * эти дни, а вторник, четверг и выходные остаются днями отдыха.
 */
