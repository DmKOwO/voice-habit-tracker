package com.voicehabit.tracker.core.analysis

import java.util.Locale

/**
 * H1. Заголовок задачи, выросшей из пункта «что дальше» конспекта.
 *
 * ## Почему отдельный объект, а не приватная функция парсера
 *
 * Один и тот же пункт конспекта попадает в задачу двумя путями: автоматически при
 * разборе в режиме [com.voicehabit.tracker.domain.model.IntentMode.MIXED] и вручную
 * по кнопке «→ задача» в читалке. Пока логика жила в парсере, ручной путь давал
 * «Может имеет смысл сначала потестировать…», а автоматический «Потестировать
 * на десяти клиентах» — два названия одной задачи в одном списке дел.
 */
object ActionTitle {

    private val META_PATTERNS = listOf(
        Regex("\\s*через\\s+\\d+\\s*(дн[\\p{L}]*|день|дня|дней|недел[\\p{L}]*|месяц[\\p{L}]*)"),
        Regex("\\s*каждый\\s+(день|утро|вечер|час[\\p{L}]*|раз)"),
        Regex("\\s*кажду(я|ю)?\\s+(понедельник[\\p{L}]*|вторник[\\p{L}]*|сред[еу]|четверг[\\p{L}]*|пятниц[\\p{L}]*|суббот[\\p{L}]*|воскресень[\\p{L}]*|неделю)"),
        Regex("\\s*(?<!\\p{L})(послезавтра|сегодня|завтра)(?!\\p{L})"),
        Regex("\\s*в\\s+(?<!\\p{L})(понедельник[\\p{L}]*|вторник[\\p{L}]*|сред[еу]|четверг[\\p{L}]*|пятниц[\\p{L}]*|суббот[\\p{L}]*|воскресень[\\p{L}]*)(?!\\p{L})"),
        Regex("\\s*[кд]о\\s+\\d{1,2}[:.]\\d{2}"),
        Regex("\\s*в\\s+\\d{1,2}[:.]\\d{2}"),
        Regex("\\s*\\d{1,2}[:.]\\d{2}"),
        Regex("\\s*\\d{1,2}\\s*час(?:ов|а)?(\\s*\\d{1,2}\\s*мин[\\p{L}]*)?"),
        Regex("\\s*(?<!\\p{L})(утром|днем|днём|вечером|ночью)(?!\\p{L})"),
        Regex("\\s*(?<!\\p{L})(ежедневно|ежедневный|постоянно|регулярно|систематически|привычк[аиуе]|привычка)(?!\\p{L})"),
        Regex("\\s*(?<!\\p{L})(срочно|важно|обязательно|очень|весьма|крайне)(?!\\p{L})")
    )

    /**
     * Слова, которые остаются брошенными после срезания мета-разметки.
     *
     * «очень срочно сдать отчёт» без «очень» в списке превращалось в «очень с сдать
     * отчёт» — сначала висящее «очень », потом ещё и оставшееся от «срочно» «с ».
     */
    private val ORPHANS = listOf(
        "и", "а", "но", "также", "так же", "итак", "же", "бы", "то", "прям", "очень",
        "весьма", "крайне", "что бы", "ну", "вот", "короче", "просто", "лично", "по"
    )

    /** Связки и модальные слова в начале: «и надо бы предупредить команду». */
    private val PREFIXES = listOf(
        "надо бы", "нужно бы", "стоит бы", "надо", "нужно", "стоит", "давай", "давайте",
        "имеет смысл", "может имеет смысл", "может", "стоит ли", "стоит ли имеет смысл",
        "попробуем", "попробуй", "попробовать", "хочу", "хотел", "планирую", "хотел бы",
        "и ещё", "и так же", "и также", "и потом", "и затем", "и наконец", "и",
        "а ещё", "а потом", "а также", "а", "но", "однако", "причём", "плюс", "затем",
        "далее", "потом", "после этого", "в первую очередь", "сначала",
        "собственно", "вообще", "просто"
    )

    const val MAX_LENGTH = 60

    /**
     * Вырезает из названия всё, что уже разобрано отдельно: дату, время, повторяемость,
     * слова срочности. Иначе в названии остаётся «завтра в 18:30».
     *
     * Возвращает строку в нижнем регистре, как и раньше: от неё зависят сравнения
     * по словам в [com.voicehabit.tracker.data.remote.OfflineVoiceParser].
     */
    fun stripMeta(raw: String): String {
        var text = raw.lowercase(Locale.getDefault())
        for (pattern in META_PATTERNS) {
            text = text.replace(pattern, " ")
        }
        return text.replace(Regex("^[\\s,;:.!]+|[\\s,;:.!]+$"), "")
            .replace(Regex("\\s+"), " ")
            .trim()
    }

    /**
     * Превращает фразу конспекта в название задачи: срезает мета-дату, связки и
     * модальные слова, приводит к заглавной букве.
     *
     * @param lowercaseInput `true`, если [raw] уже приведён к нижнему регистру
     *   (так его отдаёт конспект) — лишний `lowercase()` на каждом вызове не нужен.
     */
    fun from(raw: String, lowercaseInput: Boolean = false): String {
        var text = if (lowercaseInput) {
            raw.lowercase(Locale.getDefault()).let { stripped ->
                META_PATTERNS.fold(stripped) { acc, pattern -> acc.replace(pattern, " ") }
            }.replace(Regex("^[\\s,;:.!]+|[\\s,;:.!]+$"), "")
                .replace(Regex("\\s+"), " ").trim()
        } else {
            stripMeta(raw)
        }

        var changed = true
        var guard = 0
        while (changed && guard < 8) {
            changed = false
            guard++
            for (prefix in PREFIXES) {
                // Равенство тоже считается попаданием: иначе фраза «надо» без хвоста
                // превращалась в задачу «Надо».
                if (text == prefix) {
                    text = ""
                    changed = true
                    break
                }
                if (text.length > prefix.length && text.startsWith("$prefix ")) {
                    text = text.removePrefix(prefix).trimStart(' ', ',', ';', ':', '—', '–')
                    changed = true
                }
            }
        }

        // Убираем огрызки служебных слов, оставшиеся от срезанных кусков фразы.
        for (orphan in ORPHANS) {
            if (text == orphan) {
                text = ""
                break
            }
            if (text.length > orphan.length && text.startsWith("$orphan ")) {
                text = text.removePrefix("$orphan ").trimStart(' ')
            }
        }

        return text
            .replace(Regex("^[\\s,;:.!]+|[\\s,;:.!]+$"), "")
            .replace(Regex("\\s+"), " ")
            .trim()
            .take(MAX_LENGTH)
            .trim()
            .replaceFirstChar { it.uppercase() }
    }
}
